#!/usr/bin/env python3
"""Writes THIRD-PARTY-LICENSES.txt: the licenses of everything built into the release binary.

Covers the Rust crates that end up in the musl release build (normal dependencies only, no dev or
build dependencies) plus the files bundled under static/ and mibs/. License texts are taken from the
crate sources in the cargo registry and printed once per distinct text.

Usage (from the repository root, after `cargo fetch`):
    python3 -I dev/third-party-licenses.py           # rewrite the file
    python3 -I dev/third-party-licenses.py --check   # exit 1 if the file is out of date
"""

import json
import pathlib
import re
import subprocess
import sys

TARGET = "x86_64-unknown-linux-musl"
OUTPUT = pathlib.Path("THIRD-PARTY-LICENSES.txt")
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|notice|unlicense)([-._].*)?$", re.IGNORECASE)

BUNDLED = [
    ("uPlot 1.6.32", "static/vendor/uplot/", "MIT", "static/vendor/uplot/LICENSE"),
]
MIB_NOTE = (
    "Standard MIB modules (mibs/): taken from IETF RFCs (via net-snmp 5.9.4 and RFC 4133/3433, see\n"
    "mibs/README.md). The RFC copyright notices permit copying them for implementations."
)


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def shipped_packages(meta):
    """Packages reachable from the root over normal (runtime) dependency edges."""
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]
    seen, todo = set(), [root]
    while todo:
        current = todo.pop()
        for dep in nodes[current]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    return sorted((packages[i] for i in seen), key=lambda p: (p["name"].lower(), p["version"]))


def license_texts(package):
    folder = pathlib.Path(package["manifest_path"]).parent
    files = sorted(f for f in folder.iterdir() if f.is_file() and LICENSE_FILE.match(f.name))
    return [(f.name, f.read_text(encoding="utf-8", errors="replace").strip()) for f in files]


def add(texts, text, user):
    """Collects users per license text; texts differing only in whitespace count as one."""
    texts.setdefault(" ".join(text.split()), (text, []))[1].append(user)


def render(meta):
    crates = shipped_packages(meta)
    texts = {}  # whitespace-normalized text -> (text, list of "name version (file)")
    missing = []
    lines = [
        "Third-party software in opennetmon",
        "==================================",
        "",
        "Generated by dev/third-party-licenses.py from Cargo.lock for " + TARGET + "; do not edit by hand.",
        "opennetmon itself is licensed under the GNU Affero General Public License, version 3 or later (see LICENSE).",
        "",
        f"Rust crates compiled into the binary ({len(crates)})",
        "-" * 40,
    ]
    for p in crates:
        lines.append(f"{p['name']} {p['version']}: {p.get('license') or 'see license file'}"
                     + (f"  <{p['repository']}>" if p.get("repository") else ""))
        found = license_texts(p)
        if not found:
            missing.append(p)
        for name, text in found:
            add(texts, text, f"{p['name']} {p['version']} ({name})")

    lines += ["", "Bundled files", "-" * 40]
    for label, path, spdx, license_path in BUNDLED:
        lines.append(f"{label} ({path}): {spdx}")
        text = pathlib.Path(license_path).read_text(encoding="utf-8").strip()
        add(texts, text, f"{label} ({license_path})")
    lines.append(MIB_NOTE)

    if missing:
        lines += ["", "Crates without a license file in their source; their SPDX license applies:"]
        lines += [f"  {p['name']} {p['version']}: {p.get('license')}" for p in missing]

    lines += ["", "", "License texts", "=" * 40]
    for text, users in texts.values():
        lines += ["", "-" * 72, "Applies to:"]
        lines += [f"  {u}" for u in users]
        lines += ["-" * 72, "", text]
    return "\n".join(lines) + "\n"


def main():
    content = render(metadata())
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT} is out of date; run dev/third-party-licenses.py", file=sys.stderr)
            sys.exit(1)
        return
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT} ({content.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
